export function getTermPreview(text, icon) {
  const label = text?.trim() || ''
  const modifier = /^[+−-]?\d/.test(label)
  const term = modifier ? iconToNounMap[icon?.toLowerCase().trim()] : label
  if (!term) return null
  const canonical = aliasMap[term] || term
  const description = termDescriptions[term] || termDescriptions[canonical]
  if (!description) return null
  return { term, description, href: linkMap[term] || linkMap[canonical] || null }
}
